// Competitive: Higher than GoDaddy/Namecheap, lower than AWS/Azure/GCP

export interface PricingTier {
  id: string;           // plan ID — matches hosting_plans table
  name: string;         // 'Free' | 'Starter' | 'Pro' | 'Business' | 'Enterprise'
  monthlyPrice: number; // ₹/mo (0 = free)
  annualPrice: number;  // ₹/mo billed annually (usually 20% off monthly)
  highlighted?: boolean; // show as recommended
  description: string;
  features: string[];
  limits: Record<string, string>; // { requests: '100K/day', storage: '10GB', etc }
  cta: string;          // button label
  ctaPlanId?: string;   // plan ID for checkout URL (/vaulthost/checkout?plan=ctaPlanId)
}

