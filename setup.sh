#!/bin/bash
# ================================================================
#  ELSxGlobal + VaultHost — One-Shot Setup Script
#  Run this ONCE on your server after Coolify is installed.
#  Usage: bash setup.sh
# ================================================================

set -e

REPO="https://github.com/shashankoppo/elsxglobal_website.git"
PROJECT_DIR="/opt/elsxglobal"
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

ok()   { echo -e "${GREEN}✅ $1${NC}"; }
ask()  { echo -e "${YELLOW}👉 $1${NC}"; }
warn() { echo -e "${RED}⚠️  $1${NC}"; }

echo "============================================================"
echo "  ELSxGlobal + VaultHost — Server Setup"
echo "  $(date)"
echo "============================================================"
echo ""

# ── Step 1: Clone repo ───────────────────────────────────────────
ask "Step 1: Cloning repo to ${PROJECT_DIR}..."
if [ -d "$PROJECT_DIR" ]; then
  cd "$PROJECT_DIR/project"
  git pull origin main
  ok "Repo updated"
else
  git clone "$REPO" "$PROJECT_DIR"
  cd "$PROJECT_DIR/project"
  ok "Repo cloned"
fi

# ── Step 2: Collect secrets ──────────────────────────────────────
echo ""
ask "Step 2: Enter your configuration (press Enter to skip optional ones)"
echo ""

read -p "  Supabase URL          [http://supabase.elsxglobal.com]: " SUPA_URL
SUPA_URL="${SUPA_URL:-http://supabase.elsxglobal.com}"

read -p "  Supabase Anon Key     : " SUPA_ANON

read -p "  Supabase Service Role : " SUPA_SERVICE

read -p "  Database URL          [postgresql://postgres:pass@host:5432/postgres]: " DB_URL

read -p "  Razorpay Key ID       (optional, press Enter to skip): " RZPAY_ID
RZPAY_ID="${RZPAY_ID:-rzp_test_placeholder}"

read -p "  Razorpay Secret       (optional): " RZPAY_SECRET

read -p "  Site URL              [https://www.elsxglobal.com]: " SITE_URL
SITE_URL="${SITE_URL:-https://www.elsxglobal.com}"

# Generate random secrets if not provided
ADMIN_SECRET=$(openssl rand -hex 32 2>/dev/null || cat /dev/urandom | tr -dc 'a-f0-9' | head -c 64)
GW_SECRET=$(openssl rand -hex 32 2>/dev/null || cat /dev/urandom | tr -dc 'a-f0-9' | head -c 64)

# ── Step 3: Write .env ───────────────────────────────────────────
echo ""
ask "Step 3: Writing .env file..."

cat > .env << EOF
# Auto-generated by setup.sh on $(date)
# ── Supabase ──────────────────────────────────────────────────
NEXT_PUBLIC_SUPABASE_URL=${SUPA_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${SUPA_ANON}
SUPABASE_URL=${SUPA_URL}
SUPABASE_SERVICE_ROLE_KEY=${SUPA_SERVICE}
DATABASE_URL=${DB_URL}

# ── App ───────────────────────────────────────────────────────
NEXT_PUBLIC_SITE_URL=${SITE_URL}
NODE_ENV=production

# ── Payments ──────────────────────────────────────────────────
NEXT_PUBLIC_RAZORPAY_KEY_ID=${RZPAY_ID}
RAZORPAY_KEY_SECRET=${RZPAY_SECRET}

# ── Security (auto-generated) ─────────────────────────────────
ADMIN_SECRET=${ADMIN_SECRET}
ACTION_GATEWAY_SECRET=${GW_SECRET}

# ── Migrations ────────────────────────────────────────────────
SKIP_MIGRATIONS=false
MIGRATIONS_STRICT=false

# ── Backups ───────────────────────────────────────────────────
BACKUP_KEEP_DAYS=30
EOF

ok ".env written"

# ── Step 4: Set permissions ──────────────────────────────────────
echo ""
ask "Step 4: Setting script permissions..."
chmod +x scripts/entrypoint.sh
chmod +x scripts/migrate.mjs
chmod +x scripts/backup.sh
chmod +x scripts/restore.sh
chmod +x scripts/check-deployment.sh
ok "Permissions set"

# ── Step 5: Deploy with Docker Compose ──────────────────────────
echo ""
ask "Step 5: Starting with Docker Compose..."
docker compose pull 2>/dev/null || true
docker compose up -d --build
ok "Containers started"

# ── Step 6: Health check ─────────────────────────────────────────
echo ""
ask "Step 6: Waiting for app to start (30 seconds)..."
sleep 30

HTTP=$(curl -s -o /dev/null -w "%{http_code}" --max-time 10 http://localhost:80/api/health 2>/dev/null || echo "000")
if [ "$HTTP" = "200" ]; then
  ok "App is live! http://localhost:80"
else
  warn "App returned HTTP ${HTTP} — check logs: docker compose logs app"
fi

# ── Done ─────────────────────────────────────────────────────────
echo ""
echo "============================================================"
echo -e "${GREEN}  ✅ Setup complete!${NC}"
echo "============================================================"
echo ""
echo "  Useful commands:"
echo "  ─────────────────────────────────────────────────────"
echo "  View logs:        docker compose logs -f app"
echo "  Restart app:      docker compose restart app"
echo "  Backup DB now:    docker compose exec backup /backup.sh"
echo "  Restore DB:       docker compose exec backup /restore.sh"
echo "  Update & redeploy:"
echo "    git pull && docker compose up -d --build"
echo "  ─────────────────────────────────────────────────────"
echo ""
echo "  ⚠️  For Coolify: use Coolify dashboard instead of"
echo "     docker compose — Coolify manages containers for you."
echo ""
